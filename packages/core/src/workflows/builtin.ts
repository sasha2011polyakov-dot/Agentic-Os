import type { WorkflowDefinition } from './definition.ts';

const p = (path: string, dflt?: unknown) => (dflt === undefined ? { $path: path } : { $path: path, default: dflt });

/**
 * Specification pipeline (section 10 of the spec): coordinator → project inventory → evidence → quote grounding →
 * [requirements → validators → contradictions → (user resolves critical ones) → decomposition → validators →
 * writer → render → independent review → user approval] × iterations → save with traceability.
 */
export const SPEC_PIPELINE: WorkflowDefinition = {
  id: 'spec-pipeline',
  name: 'Техническое задание',
  description: 'Многоагентная подготовка технического задания по выбранным документам и проектам: свидетельства с проверкой цитат, требования, противоречия, декомпозиция, ревью, утверждение и сохранение со связями.',
  version: 1,
  category: 'spec',
  inputSchema: {
    type: 'object',
    required: ['title', 'goal'],
    additionalProperties: false,
    properties: {
      title: { type: 'string', minLength: 1, maxLength: 200, title: 'Название ТЗ' },
      goal: { type: 'string', minLength: 5, maxLength: 10000, title: 'Цель и описание задачи' },
      constraints: { type: 'array', maxItems: 50, items: { type: 'string', maxLength: 1000 }, title: 'Ограничения' },
      notes: { type: 'string', maxLength: 10000, title: 'Дополнительные пояснения' },
    },
  },
  nodes: [
    { id: 'context', type: 'function', fn: 'spec.context', title: 'Сбор контекста', input: {}, position: { x: 0, y: 0 } },
    {
      id: 'coordinator',
      type: 'agent',
      agent: 'coordinator',
      title: 'Анализ задачи',
      dependsOn: ['context'],
      input: { goal: p('input.goal'), constraints: p('input.constraints', []), sources: p('nodes.context.output.sources', []), selectedDocuments: p('nodes.context.output.selectedDocuments', []), extraNotes: p('input.notes', '') },
      position: { x: 240, y: 0 },
    },
    {
      id: 'clarify',
      type: 'approval',
      title: 'Уточняющие вопросы',
      dependsOn: ['coordinator'],
      when: { path: 'nodes.coordinator.output.missing_information', some: { field: 'blocking', equals: true } },
      prompt: { kind: 'questions', summary: p('nodes.coordinator.output.summary'), plan: p('nodes.coordinator.output.plan', []) },
      questions: { $pluck: 'nodes.coordinator.output.missing_information', where: { field: 'blocking', equals: true } },
      position: { x: 480, y: 0 },
    },
    {
      id: 'inventory',
      type: 'agent',
      agent: 'inventory-analyst',
      title: 'Анализ проектов',
      dependsOn: ['context'],
      when: { path: 'nodes.context.output.hasProjects', equals: true },
      input: { goal: p('input.goal'), inventories: p('nodes.context.output.inventories', []), selectedDocuments: p('nodes.context.output.selectedDocuments', []) },
      position: { x: 240, y: 140 },
    },
    {
      id: 'research',
      type: 'agent',
      agent: 'researcher',
      title: 'Сбор свидетельств',
      dependsOn: ['coordinator', 'clarify', 'inventory'],
      input: { goal: p('input.goal'), constraints: p('input.constraints', []), inventory_summary: p('nodes.inventory.output', {}), documents: p('nodes.context.output.selectedDocuments', []), answers: p('nodes.clarify.output.answers', []) },
      position: { x: 720, y: 70 },
    },
    { id: 'ground', type: 'function', fn: 'spec.ground_evidence', title: 'Проверка цитат', dependsOn: ['research'], input: { evidence: p('nodes.research.output.evidence', []) }, position: { x: 960, y: 70 } },
    {
      id: 'revise',
      type: 'loop',
      title: 'Подготовка и ревью ТЗ',
      dependsOn: ['ground'],
      body: ['requirements', 'req_check', 'contradictions', 'resolve', 'decompose', 'task_check', 'write', 'render', 'review', 'final'],
      maxIterations: p('limits.maxReviewIterations', 2),
      until: { all: [{ path: 'nodes.final.status', equals: 'completed' }, { path: 'nodes.final.output.decision', equals: 'approve' }] },
      extendWhen: { all: [{ path: 'nodes.final.status', equals: 'completed' }, { path: 'nodes.final.output.decision', equals: 'revise' }] },
      position: { x: 1200, y: 70 },
    },
    {
      id: 'requirements',
      type: 'agent',
      agent: 'requirements-analyst',
      title: 'Формулирование требований',
      input: {
        goal: p('input.goal'),
        constraints: p('input.constraints', []),
        evidence: p('nodes.ground.output.evidence', []),
        answers: p('nodes.clarify.output.answers', []),
        resolutions: p('nodes.resolve.output.choices', []),
        feedback: { $concat: [{ $pluck: 'nodes.review.output.defects', where: { field: 'stage', equals: 'requirements' }, field: 'description' }, p('nodes.final.output.comment')] },
      },
      position: { x: 0, y: 320 },
    },
    { id: 'req_check', type: 'function', fn: 'spec.validate_requirements', title: 'Проверка требований', dependsOn: ['requirements'], input: { requirements: p('nodes.requirements.output.requirements', []), evidence: p('nodes.ground.output.evidence', []) }, position: { x: 240, y: 320 } },
    {
      id: 'contradictions',
      type: 'agent',
      agent: 'contradiction-checker',
      title: 'Поиск противоречий',
      dependsOn: ['req_check'],
      input: { requirements: p('nodes.requirements.output.requirements', []), evidence: p('nodes.ground.output.evidence', []), deterministic_findings: p('nodes.req_check.output.findings', []) },
      position: { x: 480, y: 320 },
    },
    {
      id: 'resolve',
      type: 'approval',
      title: 'Решение критичных противоречий',
      dependsOn: ['contradictions'],
      when: { path: 'nodes.contradictions.output.issues', some: { field: 'severity', equals: 'critical' } },
      prompt: { kind: 'resolutions', issues: { $pluck: 'nodes.contradictions.output.issues', where: { field: 'severity', equals: 'critical' } } },
      position: { x: 720, y: 320 },
    },
    {
      id: 'decompose',
      type: 'agent',
      agent: 'decomposer',
      title: 'Декомпозиция на задачи',
      dependsOn: ['resolve'],
      input: {
        requirements: p('nodes.requirements.output.requirements', []),
        resolutions: p('nodes.resolve.output.choices', []),
        inventory_summary: p('nodes.inventory.output', {}),
        feedback: { $concat: [{ $pluck: 'nodes.review.output.defects', where: { field: 'stage', equals: 'decomposition' }, field: 'description' }] },
      },
      position: { x: 960, y: 320 },
    },
    { id: 'task_check', type: 'function', fn: 'spec.validate_tasks', title: 'Проверка декомпозиции', dependsOn: ['decompose'], input: { tasks: p('nodes.decompose.output.tasks', []), requirements: p('nodes.requirements.output.requirements', []) }, position: { x: 1200, y: 320 } },
    {
      id: 'write',
      type: 'agent',
      agent: 'spec-writer',
      title: 'Написание ТЗ',
      dependsOn: ['task_check'],
      input: {
        title: p('input.title'),
        goal: p('input.goal'),
        project_context: p('nodes.inventory.output', {}),
        requirements: p('nodes.requirements.output.requirements', []),
        tasks: p('nodes.decompose.output.tasks', []),
        evidence: p('nodes.ground.output.evidence', []),
        issues: p('nodes.contradictions.output.issues', []),
        resolutions: p('nodes.resolve.output.choices', []),
        open_questions: p('nodes.requirements.output.open_questions', []),
        feedback: { $concat: [{ $pluck: 'nodes.review.output.defects', where: { field: 'stage', equals: 'spec' }, field: 'description' }, p('nodes.final.output.comment')] },
      },
      position: { x: 0, y: 480 },
    },
    {
      id: 'render',
      type: 'function',
      fn: 'spec.render',
      title: 'Сборка документа',
      dependsOn: ['write'],
      input: {
        title: p('input.title'),
        goal: p('input.goal'),
        writer: p('nodes.write.output'),
        requirements: p('nodes.requirements.output.requirements', []),
        tasks: p('nodes.decompose.output.tasks', []),
        evidence: p('nodes.ground.output.evidence', []),
        issues: p('nodes.contradictions.output.issues', []),
        resolutions: p('nodes.resolve.output.choices', []),
        requirementCheck: p('nodes.req_check.output'),
        taskCheck: p('nodes.task_check.output'),
      },
      position: { x: 240, y: 480 },
    },
    {
      id: 'review',
      type: 'agent',
      agent: 'spec-reviewer',
      title: 'Независимое ревью',
      dependsOn: ['render'],
      input: {
        spec_markdown: p('nodes.render.output.markdown', ''),
        requirements: p('nodes.requirements.output.requirements', []),
        tasks: p('nodes.decompose.output.tasks', []),
        evidence: p('nodes.ground.output.evidence', []),
        issues: p('nodes.contradictions.output.issues', []),
        validator_findings: p('nodes.render.output.findings', []),
      },
      position: { x: 480, y: 480 },
    },
    {
      id: 'final',
      type: 'approval',
      title: 'Утверждение ТЗ',
      dependsOn: ['review'],
      when: { any: [{ all: [{ path: 'nodes.review.output.verdict', equals: 'pass' }, { path: 'nodes.render.output.blocking', equals: 0 }] }, { path: 'loop.isLast', equals: true }] },
      prompt: { kind: 'document', markdown: p('nodes.render.output.markdown', ''), metrics: p('nodes.render.output.metrics', {}), findings: p('nodes.render.output.findings', []), review: p('nodes.review.output'), iteration: p('loop.number') },
      allowRevise: true,
      onReject: 'cancel',
      position: { x: 720, y: 480 },
    },
    {
      id: 'save',
      type: 'function',
      fn: 'spec.save',
      title: 'Сохранение ТЗ, требований и задач',
      dependsOn: ['revise'],
      when: { all: [{ path: 'nodes.final.status', equals: 'completed' }, { path: 'nodes.final.output.decision', equals: 'approve' }] },
      input: {
        title: p('input.title'),
        goal: p('input.goal'),
        writer: p('nodes.write.output'),
        requirements: p('nodes.requirements.output.requirements', []),
        tasks: p('nodes.decompose.output.tasks', []),
        evidence: p('nodes.ground.output.evidence', []),
        issues: p('nodes.contradictions.output.issues', []),
        resolutions: p('nodes.resolve.output.choices', []),
        review: p('nodes.review.output'),
        requirementCheck: p('nodes.req_check.output'),
        taskCheck: p('nodes.task_check.output'),
      },
      position: { x: 1440, y: 70 },
    },
  ],
  output: {
    specDocId: p('nodes.save.output.specDocId'),
    specPath: p('nodes.save.output.specPath'),
    requirementDocs: p('nodes.save.output.requirementDocs', []),
    tasks: p('nodes.save.output.tasks', []),
    metrics: p('nodes.render.output.metrics', {}),
    reviewVerdict: p('nodes.review.output.verdict'),
    evidence: p('nodes.ground.output.stats'),
  },
};

/** Web research: local knowledge → plan → search & read sources → code-verified quotes → report ⇄ review → save. */
export const RESEARCH_PIPELINE: WorkflowDefinition = {
  id: 'web-research',
  name: 'Веб-исследование',
  description: 'Исследование вопроса по интернет-источникам: план поиска, чтение страниц, программная проверка цитат, отчёт с источниками и датами, независимое ревью.',
  version: 1,
  category: 'research',
  inputSchema: {
    type: 'object',
    required: ['question'],
    additionalProperties: false,
    properties: {
      question: { type: 'string', minLength: 5, maxLength: 2000, title: 'Вопрос исследования' },
      constraints: { type: 'array', maxItems: 20, items: { type: 'string', maxLength: 500 }, title: 'Ограничения (источники, период, язык)' },
      maxSources: { type: 'integer', minimum: 1, maximum: 15, title: 'Максимум источников' },
      reviewBeforeSave: { type: 'boolean', title: 'Показать отчёт перед сохранением' },
      save: { type: 'boolean', title: 'Сохранить отчёт в базу знаний' },
    },
  },
  nodes: [
    { id: 'local', type: 'function', fn: 'research.local', title: 'Что уже известно', input: { question: p('input.question') }, position: { x: 0, y: 0 } },
    { id: 'plan', type: 'agent', agent: 'research-planner', title: 'План исследования', dependsOn: ['local'], input: { question: p('input.question'), constraints: p('input.constraints', []), known_local: p('nodes.local.output.findings', []) }, position: { x: 240, y: 0 } },
    {
      id: 'search',
      type: 'agent',
      agent: 'web-researcher',
      title: 'Поиск и чтение источников',
      dependsOn: ['plan'],
      input: { question: p('input.question'), subquestions: p('nodes.plan.output.subquestions', []), queries: p('nodes.plan.output.queries', []), max_sources: p('input.maxSources', 6), local_findings: p('nodes.local.output.findings', []) },
      timeoutMs: 900_000,
      position: { x: 480, y: 0 },
    },
    { id: 'ground', type: 'function', fn: 'research.ground_claims', title: 'Проверка цитат', dependsOn: ['search'], input: { claims: p('nodes.search.output.claims', []), sources: p('nodes.search.output.sources', []) }, position: { x: 720, y: 0 } },
    {
      id: 'report',
      type: 'loop',
      title: 'Отчёт и ревью',
      dependsOn: ['ground'],
      body: ['write', 'review'],
      maxIterations: p('limits.maxReviewIterations', 2),
      until: { path: 'nodes.review.output.verdict', equals: 'pass' },
      position: { x: 960, y: 0 },
    },
    {
      id: 'write',
      type: 'agent',
      agent: 'research-writer',
      title: 'Отчёт',
      input: {
        question: p('input.question'),
        claims: p('nodes.ground.output.claims', []),
        sources: p('nodes.search.output.sources', []),
        conflicts: p('nodes.search.output.conflicts', []),
        gaps: p('nodes.search.output.gaps', []),
        local_findings: p('nodes.local.output.findings', []),
        feedback: { $concat: [{ $pluck: 'nodes.review.output.defects', field: 'description' }, p('nodes.review.output.unsupported_statements', [])] },
      },
      position: { x: 0, y: 200 },
    },
    { id: 'review', type: 'agent', agent: 'research-reviewer', title: 'Ревью отчёта', dependsOn: ['write'], input: { report: p('nodes.write.output'), claims: p('nodes.ground.output.claims', []), sources: p('nodes.search.output.sources', []) }, position: { x: 240, y: 200 } },
    {
      id: 'approve',
      type: 'approval',
      title: 'Просмотр отчёта',
      dependsOn: ['report'],
      when: { path: 'input.reviewBeforeSave', equals: true },
      prompt: { kind: 'document', markdown: p('nodes.write.output.markdown_body', ''), review: p('nodes.review.output'), stats: p('nodes.ground.output.stats') },
      onReject: 'cancel',
      position: { x: 1200, y: 0 },
    },
    {
      id: 'save',
      type: 'function',
      fn: 'research.save',
      title: 'Сохранение отчёта',
      dependsOn: ['approve'],
      when: { not: { path: 'input.save', equals: false } },
      input: { question: p('input.question'), report: p('nodes.write.output'), claims: p('nodes.ground.output.claims', []), sources: p('nodes.search.output.sources', []) },
      position: { x: 1440, y: 0 },
    },
  ],
  output: { docId: p('nodes.save.output.docId'), path: p('nodes.save.output.path'), stats: p('nodes.ground.output.stats'), verdict: p('nodes.review.output.verdict'), report: p('nodes.write.output') },
};

export const BUILTIN_WORKFLOWS = [SPEC_PIPELINE, RESEARCH_PIPELINE];
